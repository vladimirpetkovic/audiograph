// Regenerates pro/templates.js from the original Audiograph's built-in presets.
// Each preset layer keeps only the parameters that differ from the original's defaults.
// Usage: node tests/gen-pro-templates.cjs
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  try{
    const page=await browser.newPage();
    await page.goto('file://'+path.join(root,'index.html'));
    await page.waitForFunction(()=>typeof builtinPresets==='object'&&typeof getDefaultLayerParams==='function');
    const out=await page.evaluate(()=>{
      const d=getDefaultLayerParams(),same=(a,b)=>JSON.stringify(a)===JSON.stringify(b),pfx0=pfxNorm({});
      const title=k=>k.replace(/_/g,' ').replace(/^./,c=>c.toUpperCase());
      return Object.entries(builtinPresets).map(([key,v])=>{
        const fx={};for(const [k,x] of Object.entries(v.postFx||{}))if(k!=='enabled'&&!same(x,pfx0[k]))fx[k]=x;
        const eq=v.eq&&Object.entries(v.eq).some(([k,x])=>k!=='smoothing'&&x!==100)?Object.fromEntries(Object.entries(v.eq).filter(([k])=>k!=='smoothing')):null;
        const layers=(v.stackLayouts||[]).map(l=>{
          const look={};
          for(const [k,x] of Object.entries(l.params||{})){
            if(same(x,d[k]))continue;
            if(k==='_postFx'){if(!x||!x.enabled)continue;const o={enabled:true};for(const [pk,pv] of Object.entries(x))if(pk!=='enabled'&&!same(pv,pfx0[pk]))o[pk]=pv;look[k]=o;continue;}
            look[k]=x;
          }
          return {layout:l.layout,opacity:l.opacity??100,look};
        });
        return {key,name:title(key),bg:v.canvasBg||'#0f0f12',postFx:v.postFx?.enabled?fx:{},eq,bass:v.bass||null,dynamics:v.dynamics??null,layers};
      });
    });
    // The 3D cloner's presets become Pro templates built from 3D nodes: [name, knob values, option choices].
    const cloner=await page.evaluate(()=>AG_SIM_PRESETS.simcloner.map(([name,knobs,opts])=>({name,knobs,opts:opts||{}})));
    const js='// Generated by tests/gen-pro-templates.cjs from the original Audiograph built-in presets. Do not edit by hand.\n'+
      'export const ORIGINAL_PRESETS='+JSON.stringify(out)+';\n'+'export const CLONER_PRESETS='+JSON.stringify(cloner)+';\n';
    fs.writeFileSync(path.join(root,'pro/templates.js'),js);
    console.log(`Wrote ${out.length} presets and ${cloner.length} cloner presets, ${(js.length/1024).toFixed(1)} KB`);
  }finally{await browser.close();}
})();
