const assert=require('node:assert/strict');
(async()=>{
  const {RigidWorld,instanceCollider}=await import('../pro/rigid.js');
  const props={rigidBody:true,collisionShape:'auto',mass:1,bounce:1,friction:0,damping:0,soundForce:0};
  const ground={enabled:false,visible:false,height:-1,size:20};
  const u=new Float32Array(1264);u[31]=1;u[89]=u[90]=u[91]=1;
  const bounds=[{center:[0,0,0],half:[.5,.5,.5]}];
  const data=(...positions)=>new Float32Array(positions.flatMap(p=>[...p,0,0,0,0,1,.18,0,.5,0]));
  const advance=(w,ids,seconds,g=ground)=>{for(let i=0;i<seconds*120;i++)w.begin(1/120,g,new Set(ids));};
  const w=new RigidWorld();
  w.register('objects','a',data([-1,0,0]),u,bounds,['sphere'],props,{});
  w.register('clones','b',data([1,0,0],[3,0,0]),u,bounds,['sphere'],props,{});
  w.groups.get('objects').bodies[0].velocity.x=2;
  w.groups.get('clones').bodies[0].velocity.x=-2;
  advance(w,['objects','clones'],.7);
  assert.ok(w.groups.get('objects').bodies[0].velocity.x<0,'An object bounces off a clone in the shared world');
  assert.ok(w.groups.get('clones').bodies[0].velocity.x>0,'The clone receives the opposite impulse');
  w.reset();
  w.register('clones','c',data([-.8,0,0],[.8,0,0]),u,bounds,['cube'],props,{});
  w.groups.get('clones').bodies[0].velocity.x=2;
  w.groups.get('clones').bodies[1].velocity.x=-2;
  advance(w,['clones'],.6);
  assert.ok(w.groups.get('clones').bodies[0].velocity.x<0,'Instances inside one cloner collide');
  w.reset();
  const fall={...props,bounce:.85};
  w.register('float','zero-gravity',data([0,1,0]),u,bounds,['sphere'],props,{});
  advance(w,['float'],.5);
  assert.equal(w.groups.get('float').bodies[0].position.y,1,'New rigid bodies have no implicit gravity');
  w.reset();
  w.register('fall','d',data([0,1,0]),u,bounds,['sphere'],fall,{_rigidGravity:9.81});
  let bounced=false;
  for(let i=0;i<180;i++){
    w.begin(1/120,{...ground,enabled:true},new Set(['fall']));
    if(w.groups.get('fall').bodies[0].velocity.y>1)bounced=true;
  }
  assert.ok(bounced,'Ground catches and bounces falling bodies');
  assert.ok(w.groups.get('fall').bodies[0].position.y>-.6,'Body stays above the ground');
  advance(w,['fall'],2,ground);
  assert.ok(w.groups.get('fall').bodies[0].position.y<-5,'Disabling ground lets bodies fall through');
  w.reset();
  w.register('sound','e',data([0,0,0]),u,bounds,['sphere'],props,{_soundEffector:true,_rigidSoundForce:5});
  const loud=u.slice();loud.fill(.8,96,160);
  w.update('sound',loud,props,{_soundEffector:true,_rigidSoundForce:5});
  w.begin(1/120,ground,new Set(['sound']));
  assert.ok(w.groups.get('sound').bodies[0].velocity.y>1,'Sound changes apply a physical impulse');
  w.update('sound',u,props,{_rigidWind:10});
  advance(w,['sound'],.2);
  assert.ok(w.groups.get('sound').bodies[0].velocity.x>1,'A wired wind node pushes bodies');
  const shape=w.groups.get('sound').bodies[0].shapes[0],larger=u.slice();larger[89]=3;
  w.update('sound',larger,props,{});w.begin(1/120,ground,new Set(['sound']));
  assert.equal(shape.radius,1.5,'Collision bounds track object scaling');
  const before=w.stats().steps,position=w.groups.get('sound').bodies[0].position.clone();
  w.begin(0,ground,new Set(['sound']));
  assert.equal(w.stats().steps,before);assert.deepEqual(w.groups.get('sound').bodies[0].position,position,'Paused draws do not advance physics');
  w.begin(0,ground,new Set());
  assert.equal(w.stats().bodies,0,'Removed or disabled nodes release their bodies');
  assert.equal(w.world.contactmaterials.length,0,'Per-object ground contact materials are released');
  const fieldU=u.slice();fieldU[28]=1;
  w.register('field','f',data([.5,0,0]),fieldU,bounds,['sphere'],props,{_sim:{g3Field:'wave'},pG3FieldAmt:100,pG3FieldSpd:0});
  advance(w,['field'],.2);
  assert.ok(w.groups.get('field').bodies[0].velocity.y>.1,'Field effectors exert forces instead of teleporting rigid clones');
  w.reset();
  w.register('sleep','g',data([0,0,0]),u,bounds,['sphere'],{...fall,bounce:0,damping:.4},{_rigidGravity:9.81});
  advance(w,['sleep'],6,{...ground,enabled:true});
  assert.equal(w.groups.get('sleep').bodies[0].sleepState,2,'Resting bodies can sleep');
  advance(w,['sleep'],1,ground);
  assert.ok(w.groups.get('sleep').bodies[0].position.y<-2,'Disabling ground wakes resting bodies');
  w.reset();
  w.register('attracted','target',data([0,0,0]),u,bounds,['sphere'],props,{_rigidAttract:4,_attractPoint:[3,0,0]});
  advance(w,['attracted'],.4);
  assert.ok(w.groups.get('attracted').bodies[0].position.x>.1,'Attraction pulls toward a connected world-space target');
  w.reset();
  w.register('outside','circle',data([2.5,0,2.5]),u,bounds,['sphere'],props,{_rigidGravity:9.81});
  advance(w,['outside'],1,{...ground,enabled:true,shape:'circle',size:6});
  assert.ok(w.groups.get('outside').bodies[0].position.y<-2,'Circular ground does not catch bodies outside its radius');
  w.reset();
  w.register('inside','square',data([2.5,0,2.5]),u,bounds,['sphere'],{...props,bounce:0},{_rigidGravity:9.81});
  advance(w,['inside'],1,{...ground,enabled:true,shape:'square',size:6});
  assert.ok(w.groups.get('inside').bodies[0].position.y>-.6,'Square ground catches the same corner position');
  const triangle=new Float32Array(48);triangle[16]=1;triangle[33]=1;
  triangle[15]=triangle[31]=triangle[47]=.8;
  const mesh=instanceCollider(triangle,data([-2,0,0],[2,0,0]),u,p=>p);
  assert.equal(mesh.verts.length,6,'Every static cloner instance contributes collider triangles');
  assert.equal(mesh.verts[0][0],-2);assert.equal(mesh.verts[3][0],2);
  assert.equal(instanceCollider(triangle,data([-2,0,0],[2,0,0]),u,p=>p,mesh.faces).faces,mesh.faces,'Unchanged topology reuses the collision acceleration structure');
  w.reset();
  const growing=u.slice();growing[35]=1;growing[195]=1;
  const seed=data([0,0,0]);seed[3]=1;seed[7]=2;
  w.register('growing','uniform',seed,growing,bounds,['sphere'],props,{});
  const group=w.groups.get('growing');
  assert.ok(Math.abs(group.bodies[0].position.y-.7)<1e-6,'Initial rigid geometry matches uniform grow-from-base anchoring');
  const bottomTriangle=triangle.slice();bottomTriangle[1]=bottomTriangle[17]=bottomTriangle[33]=-.7;
  const anchored=instanceCollider(bottomTriangle,seed,growing,p=>p);
  assert.ok(anchored.verts.every(v=>Math.abs(v[1]+.7)<1e-6),'Static collider bottom stays anchored under uniform sound scaling');
  growing[35]=3;w.update('growing',growing,props,{});
  assert.equal(group.data[7],4,'Uniform sound scale updates rigid instance data without compounding');
  assert.equal(group.bodies[0].shapes[0].radius,2,'Uniform sound scale updates physical collision bounds');
  assert.ok(Math.abs(group.centers[0][1]-2.1)<1e-6,'Rigid center uses the same anchor as native geometry');
  console.log('ok - Shared rigid object/clone collisions, gravity, ground, sound, forces, scaling and cleanup');
})().catch(error=>{console.error(error);process.exitCode=1;});
