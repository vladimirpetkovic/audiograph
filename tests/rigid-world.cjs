const assert=require('node:assert/strict');
(async()=>{
  const {RigidWorld,instanceCollider,instanceBoxBounds}=await import('../pro/rigid.js');
  const {TYPES,defaults,applyShapeNode}=await import('../pro/graph.js');
  const props={rigidBody:true,collisionShape:'auto',mass:1,bounce:1,friction:0,damping:0,soundForce:0};
  const ground={enabled:false,visible:false,height:-1,size:20};
  const u=new Float32Array(1264);u[31]=1;u[89]=u[90]=u[91]=1;
  const bounds=[{center:[0,0,0],half:[.5,.5,.5]}];
  const data=(...positions)=>new Float32Array(positions.flatMap(p=>[...p,0,0,0,0,1,.18,0,.5,0]));
  const advance=(w,ids,seconds,g=ground)=>{for(let i=0;i<seconds*120;i++)w.begin(1/120,g,new Set(ids));};
  const force=(type,overrides)=>applyShapeNode(type,{...defaults(type),...overrides},{});
  for(const [type,T] of Object.entries(TYPES).filter(([,T])=>T.force)){
    const background={_rigidGravity:7,_spin:2,pSpTurb:11};
    assert.deepEqual(applyShapeNode(type,{...defaults(type),intensity:0},background),background,`${type}: zero intensity bypasses the force without erasing earlier nodes`);
  }
  assert.equal(force('drag',{rigid:.1})._rigidDrag,.1,'Default intensity preserves existing damping exactly');
  assert.equal(force('turbulence',{intensity:500,amount:80,scale:30}).pSpTurbScale,30,'Intensity strengthens turbulence without changing its spatial scale');
  const forcedBody=(type,p)=>{
    const world=new RigidWorld(),mods=force(type,p);
    world.register('body',type,data([2,1,2]),u,bounds,['sphere'],props,mods);
    world.update('body',u,props,mods);
    const body=world.groups.get('body').bodies[0];
    body.velocity.set(type==='drag'?3:0,0,0);
    advance(world,['body'],.25);
    const result={velocity:body.velocity.toArray(),position:body.position.toArray(),damping:body.linearDamping};
    world.reset();return result;
  };
  for(const [type,p] of [['gravity',{rigid:80}],['wind',{rigid:50}],['swirl',{rigid:8}],['attract',{rigid:10}],['turbulence',{rigid:100}]]){
    const off=forcedBody(type,{...p,intensity:0}),on=forcedBody(type,{...p,intensity:100}),strong=forcedBody(type,{...p,intensity:500});
    assert.ok(on.velocity.some((v,i)=>Math.abs(v-off.velocity[i])>.05),`${type} physically moves bodies`);
    const speed=r=>Math.hypot(...r.velocity);
    assert.ok(speed(strong)>speed(on)*1.5,`${type} intensity measurably strengthens the force`);
    assert.ok([...strong.velocity,...strong.position].every(Number.isFinite),`${type} stays finite at amplified values`);
  }
  const normalDrag=forcedBody('drag',{rigid:.8,intensity:100}),strongDrag=forcedBody('drag',{rigid:.8,intensity:1000});
  assert.ok(strongDrag.velocity[0]<normalDrag.velocity[0]*.1,'High drag intensity increases damping instead of producing an invalid Cannon coefficient');
  assert.ok(strongDrag.damping>=0&&strongDrag.damping<=1&&strongDrag.velocity.every(Number.isFinite));
  const corners=Array.from({length:8},(_,i)=>[0,1,2].map(j=>(i&(1<<j)?.5:-.5)));
  const quads=[[0,1,3,2],[4,6,7,5],[0,4,5,1],[2,3,7,6],[0,2,6,4],[1,5,7,3]];
  const triangles=quads.flatMap(([a,b,c,d])=>[a,b,c,a,c,d]);
  const cube=new Float32Array(triangles.length*16);
  triangles.forEach((id,i)=>cube.set(corners[id],i*16));
  const transformed=data([0,1,0]);transformed.set([.2,.3,-.4],4);transformed[7]=.6;
  const stretched=u.slice();stretched[89]=2;stretched[90]=3;stretched[91]=.5;stretched[195]=.8;
  const map=v=>[v[0]+2,.5*v[1]-.2*v[2]+3,v[2]-1];
  const full=instanceCollider(cube,transformed,stretched,map),box=instanceBoxBounds(cube,transformed,stretched,map);
  assert.deepEqual(box.min,[0,1,2].map(j=>Math.min(...full.verts.map(v=>v[j]))),'Lightweight cube bounds match full transformed collider geometry');
  assert.deepEqual(box.max,[0,1,2].map(j=>Math.max(...full.verts.map(v=>v[j]))));
  const w=new RigidWorld();
  w.register('objects','a',data([-1,0,0]),u,bounds,['sphere'],props,{});
  w.register('clones','b',data([1,0,0],[3,0,0]),u,bounds,['sphere'],props,{});
  w.groups.get('objects').bodies[0].velocity.x=2;
  w.groups.get('clones').bodies[0].velocity.x=-2;
  advance(w,['objects','clones'],.7);
  assert.ok(w.groups.get('objects').bodies[0].velocity.x<0,'An object bounces off a clone in the shared world');
  assert.ok(w.groups.get('clones').bodies[0].velocity.x>0,'The clone receives the opposite impulse');
  w.reset();
  w.register('clones','c',data([-.8,0,0],[.8,0,0]),u,bounds,['cube'],props,{});
  w.groups.get('clones').bodies[0].velocity.x=2;
  w.groups.get('clones').bodies[1].velocity.x=-2;
  advance(w,['clones'],.6);
  assert.ok(w.groups.get('clones').bodies[0].velocity.x<0,'Instances inside one cloner collide');
  w.reset();
  const fall={...props,bounce:.85};
  w.register('float','zero-gravity',data([0,1,0]),u,bounds,['sphere'],props,{});
  advance(w,['float'],.5);
  assert.equal(w.groups.get('float').bodies[0].position.y,1,'New rigid bodies have no implicit gravity');
  w.update('float',u,props,{_rigidGravity:9.81});
  advance(w,['float'],.25);
  assert.ok(w.groups.get('float').bodies[0].position.y<.8,'Connected Gravity affects rigid bodies');
  w.reset();
  const gravityBody={...props,rigidBody:false,gravityBody:true};
  w.register('scene-clones','node-gravity',data([0,1,0]),u,bounds,['cube'],gravityBody,{_rigidGravity:9.81,_rigidWind:10});
  advance(w,['scene-clones'],.25);
  const sceneClone=w.groups.get('scene-clones').bodies[0];
  assert.ok(sceneClone.position.y<.8&&sceneClone.velocity.y<0,'Attached Gravity moves Cloners without Rigid body');
  assert.equal(sceneClone.position.x,0,'Gravity-started Cloners still ignore other Forces');
  const fallingY=sceneClone.position.y;
  w.update('scene-clones',u,gravityBody,{_rigidGravity:0});
  advance(w,['scene-clones'],.25);
  assert.equal(w.groups.get('scene-clones').bodies[0],sceneClone,'Returning Gravity to zero preserves the body');
  assert.ok(sceneClone.position.y<fallingY,'Returning Gravity to zero preserves momentum');
  w.reset();
  w.register('cancel','gravity-zero',data([0,1,0]),u,bounds,['sphere'],props,{_rigidGravity:0});
  advance(w,['cancel'],.5);
  assert.equal(w.groups.get('cancel').bodies[0].position.y,1,'Zero Gravity does not accelerate bodies');
  w.update('cancel',u,props,{_rigidGravity:-9.81});
  advance(w,['cancel'],.25);
  assert.ok(w.groups.get('cancel').bodies[0].position.y>1.2,'Negative Gravity pulls bodies upward');
  w.reset();
  w.register('fall','d',data([0,1,0]),u,bounds,['sphere'],fall,{_rigidGravity:9.81});
  let bounced=false;
  for(let i=0;i<180;i++){
    w.begin(1/120,{...ground,enabled:true},new Set(['fall']));
    if(w.groups.get('fall').bodies[0].velocity.y>1)bounced=true;
  }
  assert.ok(bounced,'Ground catches and bounces falling bodies');
  assert.ok(w.groups.get('fall').bodies[0].position.y>-.6,'Body stays above the ground');
  advance(w,['fall'],2,ground);
  assert.ok(w.groups.get('fall').bodies[0].position.y<-5,'Disabling ground lets bodies fall through');
  w.reset();
  w.register('sound','e',data([0,0,0]),u,bounds,['sphere'],props,{_soundEffector:true,_rigidSoundForce:5});
  const loud=u.slice();loud.fill(.8,96,160);
  w.update('sound',loud,props,{_soundEffector:true,_rigidSoundForce:5});
  w.begin(1/120,ground,new Set(['sound']));
  assert.ok(w.groups.get('sound').bodies[0].velocity.y>1,'Sound changes apply a physical impulse');
  w.update('sound',u,props,{_rigidWind:10});
  advance(w,['sound'],.2);
  assert.ok(w.groups.get('sound').bodies[0].velocity.x>1,'A wired wind node pushes bodies');
  const shape=w.groups.get('sound').bodies[0].shapes[0],larger=u.slice();larger[89]=3;
  w.update('sound',larger,props,{});w.begin(1/120,ground,new Set(['sound']));
  assert.equal(shape.radius,1.5,'Collision bounds track object scaling');
  const before=w.stats().steps,position=w.groups.get('sound').bodies[0].position.clone();
  w.begin(0,ground,new Set(['sound']));
  assert.equal(w.stats().steps,before);assert.deepEqual(w.groups.get('sound').bodies[0].position,position,'Paused draws do not advance physics');
  w.begin(0,ground,new Set());
  assert.equal(w.stats().bodies,0,'Removed or disabled nodes release their bodies');
  assert.equal(w.world.contactmaterials.length,0,'Per-object ground contact materials are released');
  const fieldU=u.slice();fieldU[28]=1;
  w.register('field','f',data([.5,0,0]),fieldU,bounds,['sphere'],props,{_sim:{g3Field:'wave'},pG3FieldAmt:100,pG3FieldSpd:0});
  advance(w,['field'],.2);
  assert.ok(w.groups.get('field').bodies[0].velocity.y>.1,'Field effectors exert forces instead of teleporting rigid clones');
  w.reset();
  w.register('sleep','g',data([0,0,0]),u,bounds,['sphere'],{...fall,bounce:0,damping:.4},{_rigidGravity:9.81});
  advance(w,['sleep'],6,{...ground,enabled:true});
  assert.equal(w.groups.get('sleep').bodies[0].sleepState,2,'Resting bodies can sleep');
  advance(w,['sleep'],1,ground);
  assert.ok(w.groups.get('sleep').bodies[0].position.y<-2,'Disabling ground wakes resting bodies');
  w.reset();
  w.register('attracted','target',data([0,0,0]),u,bounds,['sphere'],props,{_rigidAttract:4,_attractPoint:[3,0,0]});
  advance(w,['attracted'],.4);
  assert.ok(w.groups.get('attracted').bodies[0].position.x>.1,'Attraction pulls toward a connected world-space target');
  w.reset();
  w.register('outside','circle',data([2.5,0,2.5]),u,bounds,['sphere'],props,{_rigidGravity:9.81});
  advance(w,['outside'],1,{...ground,enabled:true,shape:'circle',size:6});
  assert.ok(w.groups.get('outside').bodies[0].position.y<-2,'Circular ground does not catch bodies outside its radius');
  w.reset();
  w.register('inside','square',data([2.5,0,2.5]),u,bounds,['sphere'],{...props,bounce:0},{_rigidGravity:9.81});
  advance(w,['inside'],1,{...ground,enabled:true,shape:'square',size:6});
  assert.ok(w.groups.get('inside').bodies[0].position.y>-.6,'Square ground catches the same corner position');
  const triangle=new Float32Array(48);triangle[16]=1;triangle[33]=1;
  triangle[15]=triangle[31]=triangle[47]=.8;
  const mesh=instanceCollider(triangle,data([-2,0,0],[2,0,0]),u,p=>p);
  assert.equal(mesh.verts.length,6,'Every static cloner instance contributes collider triangles');
  assert.equal(mesh.verts[0][0],-2);assert.equal(mesh.verts[3][0],2);
  assert.equal(instanceCollider(triangle,data([-2,0,0],[2,0,0]),u,p=>p,mesh.faces).faces,mesh.faces,'Unchanged topology reuses the collision acceleration structure');
  w.reset();
  const growing=u.slice();growing[35]=1;growing[195]=1;
  const seed=data([0,0,0]);seed[3]=1;seed[7]=2;
  w.register('growing','uniform',seed,growing,bounds,['sphere'],props,{});
  const group=w.groups.get('growing');
  assert.ok(Math.abs(group.bodies[0].position.y-.7)<1e-6,'Initial rigid geometry matches uniform grow-from-base anchoring');
  const bottomTriangle=triangle.slice();bottomTriangle[1]=bottomTriangle[17]=bottomTriangle[33]=-.7;
  const anchored=instanceCollider(bottomTriangle,seed,growing,p=>p);
  assert.ok(anchored.verts.every(v=>Math.abs(v[1]+.7)<1e-6),'Static collider bottom stays anchored under uniform sound scaling');
  growing[35]=3;w.update('growing',growing,props,{});
  assert.equal(group.data[7],4,'Uniform sound scale updates rigid instance data without compounding');
  assert.equal(group.bodies[0].shapes[0].radius,2,'Uniform sound scale updates physical collision bounds');
  assert.ok(Math.abs(group.centers[0][1]-2.1)<1e-6,'Rigid center uses the same anchor as native geometry');
  w.reset();
  const colliderProps={...props,rigidBody:false,gravityBody:true};
  const initial=data([-1,1,0],[1,1,0]);
  w.register('effector','persistent',initial,u,bounds,['cube'],colliderProps,{_rigidWind:10});
  const colliders=w.groups.get('effector'),bodies=colliders.bodies.slice();
  advance(w,['effector'],.25);
  assert.ok(colliders.bodies.every(b=>b.position.y===1&&b.velocity.lengthSquared()===0),'Collider-only clones have no implicit gravity and ignore Force nodes');
  const expanded=initial.slice();expanded[7]=expanded[19]=3;
  w.applyEffects('effector',expanded,u);
  advance(w,['effector'],.5);
  assert.ok(Math.abs(colliders.bodies[1].position.x-colliders.bodies[0].position.x-2)<1e-6,'Gravity-only clones may overlap without object collision impulses');
  w.update('effector',u,{...colliderProps,rigidBody:true},{});
  advance(w,['effector'],.5);
  assert.ok(colliders.bodies[1].position.x-colliders.bodies[0].position.x>=2.99,'Effector-expanded clones separate instead of overlapping');
  assert.ok(colliders.bodies[0].velocity.x<0&&colliders.bodies[1].velocity.x>0,'Expanding rigid bodies exchange collision impulses');
  assert.deepEqual(colliders.bodies,bodies,'Effector changes retain the existing physical bodies');
  const moved=expanded.slice();moved[0]+=2;moved[12]+=2;moved[4]=moved[16]=Math.PI/4;
  const physical=colliders.bodies.map(b=>b.position.x);
  w.applyEffects('effector',moved,u);
  assert.ok(colliders.bodies.every((b,i)=>Math.abs(b.position.x-physical[i]-2)<1e-6),'Effector position changes preserve collision-resolved offsets');
  const rotated=colliders.bodies[0].quaternion;
  assert.ok(Math.abs(rotated.x)>.1,'Effector rotations update collision orientations');
  const anisotropic=u.slice();anisotropic[1260]=anisotropic[1262]=1;
  w.update('effector',anisotropic,colliderProps,{});
  assert.ok(colliders.bodies.some(b=>Math.abs(b.shapes[0].halfExtents.x-b.shapes[0].halfExtents.z)>.01),'Random X/Z scaling updates per-instance collision bounds');
  console.log('ok - Shared rigid object/clone collisions, gravity, ground, sound, forces, scaling and cleanup');
})().catch(error=>{console.error(error);process.exitCode=1;});
