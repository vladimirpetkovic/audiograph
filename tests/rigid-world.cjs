const assert=require('node:assert/strict');
(async()=>{
  const {RigidWorld}=await import('../pro/rigid.js');
  const props={rigidBody:true,collisionShape:'auto',mass:1,bounce:1,friction:0,damping:0,bodyGravity:0,soundForce:0};
  const ground={enabled:false,visible:false,height:-1,size:20};
  const u=new Float32Array(1264);u[31]=1;u[89]=u[90]=u[91]=1;
  const bounds=[{center:[0,0,0],half:[.5,.5,.5]}];
  const data=(...positions)=>new Float32Array(positions.flatMap(p=>[...p,0,0,0,0,1,.18,0,.5,0]));
  const advance=(w,ids,seconds,g=ground)=>{for(let i=0;i<seconds*120;i++)w.begin(1/120,g,new Set(ids));};
  const w=new RigidWorld();
  w.register('objects','a',data([-1,0,0]),u,bounds,['sphere'],props,{});
  w.register('clones','b',data([1,0,0],[3,0,0]),u,bounds,['sphere'],props,{});
  w.groups.get('objects').bodies[0].velocity.x=2;
  w.groups.get('clones').bodies[0].velocity.x=-2;
  advance(w,['objects','clones'],.7);
  assert.ok(w.groups.get('objects').bodies[0].velocity.x<0,'An object bounces off a clone in the shared world');
  assert.ok(w.groups.get('clones').bodies[0].velocity.x>0,'The clone receives the opposite impulse');
  w.reset();
  w.register('clones','c',data([-.8,0,0],[.8,0,0]),u,bounds,['cube'],props,{});
  w.groups.get('clones').bodies[0].velocity.x=2;
  w.groups.get('clones').bodies[1].velocity.x=-2;
  advance(w,['clones'],.6);
  assert.ok(w.groups.get('clones').bodies[0].velocity.x<0,'Instances inside one cloner collide');
  w.reset();
  const fall={...props,bodyGravity:9.81,bounce:.85};
  w.register('fall','d',data([0,1,0]),u,bounds,['sphere'],fall,{});
  let bounced=false;
  for(let i=0;i<180;i++){
    w.begin(1/120,{...ground,enabled:true},new Set(['fall']));
    if(w.groups.get('fall').bodies[0].velocity.y>1)bounced=true;
  }
  assert.ok(bounced,'Ground catches and bounces falling bodies');
  assert.ok(w.groups.get('fall').bodies[0].position.y>-.6,'Body stays above the ground');
  advance(w,['fall'],2,ground);
  assert.ok(w.groups.get('fall').bodies[0].position.y<-5,'Disabling ground lets bodies fall through');
  w.reset();
  w.register('sound','e',data([0,0,0]),u,bounds,['sphere'],{...props,soundForce:5},{});
  const loud=u.slice();loud.fill(.8,96,160);
  w.update('sound',loud,{...props,soundForce:5},{});
  w.begin(1/120,ground,new Set(['sound']));
  assert.ok(w.groups.get('sound').bodies[0].velocity.y>1,'Sound changes apply a physical impulse');
  w.update('sound',u,props,{_rigidWind:10});
  advance(w,['sound'],.2);
  assert.ok(w.groups.get('sound').bodies[0].velocity.x>1,'A wired wind node pushes bodies');
  const shape=w.groups.get('sound').bodies[0].shapes[0],larger=u.slice();larger[89]=3;
  w.update('sound',larger,props,{});w.begin(1/120,ground,new Set(['sound']));
  assert.equal(shape.radius,1.5,'Collision bounds track object scaling');
  const before=w.stats().steps,position=w.groups.get('sound').bodies[0].position.clone();
  w.begin(0,ground,new Set(['sound']));
  assert.equal(w.stats().steps,before);assert.deepEqual(w.groups.get('sound').bodies[0].position,position,'Paused draws do not advance physics');
  w.begin(0,ground,new Set());
  assert.equal(w.stats().bodies,0,'Removed or disabled nodes release their bodies');
  assert.equal(w.world.contactmaterials.length,0,'Per-object ground contact materials are released');
  const fieldU=u.slice();fieldU[28]=1;
  w.register('field','f',data([.5,0,0]),fieldU,bounds,['sphere'],props,{_sim:{g3Field:'wave'},pG3FieldAmt:100,pG3FieldSpd:0});
  advance(w,['field'],.2);
  assert.ok(w.groups.get('field').bodies[0].velocity.y>.1,'Field effectors exert forces instead of teleporting rigid clones');
  w.reset();
  w.register('sleep','g',data([0,0,0]),u,bounds,['sphere'],{...fall,bounce:0,damping:.4},{});
  advance(w,['sleep'],6,{...ground,enabled:true});
  assert.equal(w.groups.get('sleep').bodies[0].sleepState,2,'Resting bodies can sleep');
  advance(w,['sleep'],1,ground);
  assert.ok(w.groups.get('sleep').bodies[0].position.y<-2,'Disabling ground wakes resting bodies');
  console.log('ok - Shared rigid object/clone collisions, gravity, ground, sound, forces, scaling and cleanup');
})().catch(error=>{console.error(error);process.exitCode=1;});
